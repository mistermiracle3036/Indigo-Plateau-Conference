"""Approved developer-guest dialogue -> dev_lines.lua (1.1.74).

Input:  tools/team_sources/dev-guest-dialogue-approved.json -- the 28 guests'
        lines as the developer approved them on the review page
        (https://claude.ai/artifact/XX68buFw4dhWTvW9ERarGE, db collection
        `guests`), every one approved: "yeah all lines look good" (2026-10-14).
Output: dev_lines.lua, read by main.lua, which sets each guest's six lines
        before the text registry is filled. Never hand-edit the output.

Every page is checked: <= 2 lines, <= 18 characters, printable ASCII; and the
speaker-name rule the 89 normal challengers follow (chat/intro/afterWin/
afterLoss open with "NAME:", the two in-battle lines do not).

  python tools/gen_dev_lines.py [--check]
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.dirname(HERE)
SRC = os.path.join(HERE, "team_sources", "dev-guest-dialogue-approved.json")
OUT = os.path.join(MOD, "dev_lines.lua")
FIELDS = ("chat", "intro", "win", "loss", "afterWin", "afterLoss")
NAMED = {"chat", "intro", "afterWin", "afterLoss"}


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\f", "\\f") + '"'


def main(argv):
    data = json.load(open(SRC, encoding="utf-8"))
    fails = []
    lines = ["-- Generated by tools/gen_dev_lines.py from the developer-approved review",
             "-- (2026-10-14). Developer-guest dialogue; never hand-edit.",
             "return {"]
    for c in sorted(data["characters"], key=lambda c: c["order"]):
        if not c.get("approved"):
            fails.append(f"{c['key']}: not approved")
        parts = []
        for f in FIELDS:
            s = c[f]
            for page in s.split("\f"):
                rows = page.split("\n")
                if len(rows) > 2:
                    fails.append(f"{c['key']}.{f}: page with {len(rows)} lines")
                for r in rows:
                    if len(r) > 18:
                        fails.append(f"{c['key']}.{f}: {r!r} is {len(r)} chars")
                    if any(not (32 <= ord(ch) <= 126) for ch in r):
                        fails.append(f"{c['key']}.{f}: non-ASCII in {r!r}")
            named = re.match(r"^[A-Z][A-Z .&]+:", s) is not None
            if named != (f in NAMED):
                fails.append(f"{c['key']}.{f}: speaker-name rule")
            parts.append(f"{f} = {lua_str(s)}")
        lines.append(f'  ["{c["key"]}"] = {{ ' + ", ".join(parts) + " },")
    lines.append("}")
    text = "\n".join(lines) + "\n"
    for f in fails:
        print("FAIL", f)
    cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if "--check" in argv:
        if cur != text:
            print("STALE dev_lines.lua")
            return 1
    elif cur != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("wrote dev_lines.lua")
    print(f"{len(data['characters'])} guests, {len(data['characters']) * 6} lines")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
